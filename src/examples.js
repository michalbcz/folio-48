function spectrumProgram(id) {
  var i;
  for (i = 0; i < SPECTRUM_PROGRAMS.length; i++) {
    if (SPECTRUM_PROGRAMS[i].id === id) return SPECTRUM_PROGRAMS[i];
  }
  return null;
}

