function programSource(options, play) {
  return [
    "tick equ $5b00",
    "state equ $5b01",
    "px equ $5b02",
    "py equ $5b03",
    "opx equ $5b04",
    "opy equ $5b05",
    "hx equ $5b06",
    "hy equ $5b07",
    "ohx equ $5b08",
    "ohy equ $5b09",
    "score equ $5b0b",
    "keys equ $5b0c",
    "demo equ $5b0d",
    "border equ $5b0e",
    "pipx equ $5b10",
    "pipy equ $5b11",
    "opipx equ $5b12",
    "opipy equ $5b13",
    "pipi equ $5b14",
    "paper equ $5b1e",
    "framec equ $5b1f",
    "scorec equ $5b20",
    "hazardc equ $5b21",
    "",
    "org 0",
    "di",
    "im 1",
    "ld sp, $fffe",
    "xor a",
    "ld (state), a",
    "ld (tick), a",
    "ld a, " + options.paper,
    "ld (paper), a",
    "ld a, " + options.frame,
    "ld (framec), a",
    "ld a, 1",
    "ld (border), a",
    "out ($fe), a",
    "ei",
    "jp title_enter",
    "",
    "org $38",
    "ei",
    "reti",
    "",
    "org $66",
    "ret",
    "",
    "org $100",
    titleSource(),
    play,
    overSource(),
    "name_list:",
    folioList(folioCells(options.word, options.col, 4)),
    "space_list:",
    folioList(folioCells("SPACE", options.col, 12)),
    "over_list:",
    folioList(folioCells("OVER", 8, 8)),
    cellSupport()
  ].join("\n");
}

