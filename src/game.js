function folioCells(word, col, row) {
  var out = [];
  var i, y, x, glyph;
  for (i = 0; i < word.length; i++) {
    glyph = FOLIO_FONT[word.charAt(i)];
    for (y = 0; y < 5; y++) {
      for (x = 0; x < 3; x++) {
        if (glyph[y].charAt(x) === "#") out.push([col + i * 4 + x, row + y]);
      }
    }
  }
  return out;
}

function folioList(pairs) {
  var lines = [];
  var row = [];
  var i;
  for (i = 0; i < pairs.length; i++) {
    row.push(pairs[i][0]);
    row.push(pairs[i][1]);
    if (row.length >= 16) {
      lines.push("db " + row.join(","));
      row = [];
    }
  }
  if (row.length) lines.push("db " + row.join(","));
  lines.push("db $ff");
  return lines.join("\n");
}

